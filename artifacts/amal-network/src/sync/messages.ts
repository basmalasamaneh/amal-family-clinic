export const REASON_CODES = ['doctor-overlap', 'patient-overlap', 'same-day-other-clinic', 'outside-hours', 'slot-held', 'stale-version'] as const;
export type ReasonCode = (typeof REASON_CODES)[number] | 'unknown';
export function reasonCode(raw: unknown): ReasonCode {
  return typeof raw === 'string' && (REASON_CODES as readonly string[]).includes(raw) ? (raw as ReasonCode) : 'unknown';
}
