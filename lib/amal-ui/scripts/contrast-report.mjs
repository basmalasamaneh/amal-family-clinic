// Measures WCAG contrast for every text/background pairing the kit renders.
// Writes docs/contrast-report.md and exits non-zero if any pair is < 4.5:1.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(resolve(root, 'tokens.json'), 'utf8'));

const lum = (hex) => {
  const n = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(n.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

const statuses = ['booked', 'completed', 'noshow', 'conflict', 'sync', 'cancelled'];
const pairs = [
  ['body text', 'text', 'bg'], ['body text on surface', 'text', 'surface'], ['text on surface-2', 'text', 'surface-2'],
  ['muted on bg', 'muted', 'bg'], ['muted on surface', 'muted', 'surface'], ['muted/placeholder on surface-2', 'muted', 'surface-2'],
  ['navy heading on surface', 'navy', 'surface'], ['primary-text on surface', 'primary-text', 'surface'],
  ['primary-text on bg', 'primary-text', 'bg'], ['primary-text on surface-2', 'primary-text', 'surface-2'],
  ['primary-text on primary-soft (hover)', 'primary-text', 'primary-soft'],
  ['primary button', 'on-primary', 'primary'], ['primary hover', 'on-primary', 'primary-strong'], ['primary pressed', 'on-primary', 'primary-pressed'],
  ['danger button', 'on-danger', 'danger'], ['danger hover', 'on-danger', 'danger-strong'],
  ['error text on surface', 'danger-strong', 'surface'], ['disabled', 'disabled-fg', 'disabled-bg'],
  ['toast text', 'toast-fg', 'toast-bg'], ['toast accent', 'toast-accent', 'toast-bg'],
  ['swatch label', 'text', 'surface'], ['swatch hex', 'muted', 'surface'],
  ['heading on bg', 'navy', 'bg'], ['heading on muted card', 'navy', 'surface-2'],
  ['field error on bg', 'danger-strong', 'bg'], ['field error on muted card', 'danger-strong', 'surface-2'],
  ['toggle normal', 'text', 'surface-2'], ['toggle hover', 'primary-text', 'primary-soft'],
  ['secondary pressed', 'primary-text', 'surface-2'], ['ghost on bg', 'primary-text', 'bg'],
  ...statuses.map((s) => [`status ${s}`, `status-${s}-fg`, `status-${s}-bg`]),
];
const get = (m, k) => (m.raw[k] ?? m.semantic[k]).$value;
let fail = 0;
let md = '# Amal UI contrast report\n\nGenerated by `scripts/contrast-report.mjs` from `tokens.json`. Threshold: 4.5:1 (WCAG AA, normal text).\n';
for (const mode of ['light', 'dark']) {
  const m = t.color[mode];
  md += `\n## ${mode}\n\n| Pairing | Foreground | Background | Ratio | Result |\n|---|---|---|---|---|\n`;
  for (const [label, fg, bg] of pairs) {
    const r = ratio(get(m, fg), get(m, bg));
    const ok = r >= 4.5;
    if (!ok) { fail++; console.error(`FAIL ${mode} ${label} ${r.toFixed(2)}`); }
    md += `| ${label} | ${fg} ${get(m, fg)} | ${bg} ${get(m, bg)} | ${r.toFixed(2)} | ${ok ? 'pass' : 'FAIL'} |\n`;
  }
}
md += '\n## Focus indicators (non-text, minimum 3:1)\n\n| Mode | Adjacent background | Ratio | Result |\n|---|---|---|---|\n';
for (const mode of ['light', 'dark']) {
  const m = t.color[mode];
  for (const bg of ['bg', 'surface', 'surface-2']) {
    const r = ratio(get(m, 'focus-ring'), get(m, bg));
    if (r < 3) fail++;
    md += `| ${mode} | ${bg} | ${r.toFixed(2)} | ${r >= 3 ? 'pass' : 'FAIL'} |\n`;
  }
}
md += '\nFocus does not change text/background pairings. Hover and pressed semantic variants are included above. Logo lettering uses theme-aware navy and primary tokens on a transparent background; the supplied badge artwork remains unchanged. Swatch pigments have no overlaid text. Gold is documented numerically, not rendered as a UI fill outside the supplied logo and empty-state illustration.\n';
writeFileSync(resolve(root, 'docs/contrast-report.md'), md);
console.log(fail ? `${fail} failing pairs` : 'all pairs pass');
process.exit(fail ? 1 : 0);
