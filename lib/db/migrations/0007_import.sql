BEGIN;
ALTER TABLE operational.import_batches ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1;
ALTER TABLE operational.import_batches ADD COLUMN IF NOT EXISTS owner_id integer REFERENCES operational.users(id);
ALTER TABLE operational.import_batches ADD COLUMN IF NOT EXISTS owner_doctor_id integer REFERENCES operational.doctors(doctor_id);
ALTER TABLE operational.import_batches ADD COLUMN IF NOT EXISTS committed_at timestamptz;
ALTER TABLE operational.import_batches ADD COLUMN IF NOT EXISTS report jsonb;
ALTER TABLE operational.import_rows ADD COLUMN IF NOT EXISTS staging jsonb NOT NULL DEFAULT '{}'::jsonb;
-- Staging contains necessary new-patient demographics only until successful commit.
-- Verification inputs are never persisted; only an internal fingerprint of current identity.
CREATE TABLE IF NOT EXISTS operational.import_source_links (
  source_name text NOT NULL,
  source_event_id integer NOT NULL,
  source_hash text NOT NULL,
  appointment_id integer NOT NULL REFERENCES operational.appointments(appointment_id),
  batch_id integer NOT NULL REFERENCES operational.import_batches(id),
  row_id integer NOT NULL REFERENCES operational.import_rows(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(source_name,source_event_id)
);
CREATE TABLE IF NOT EXISTS operational.import_operations (
  user_id integer NOT NULL REFERENCES operational.users(id),
  client_op_id uuid NOT NULL,
  request_hash text NOT NULL,
  batch_id integer NOT NULL REFERENCES operational.import_batches(id),
  operation text NOT NULL CHECK(operation IN ('upload','commit')),
  PRIMARY KEY(user_id,client_op_id)
);
CREATE TABLE IF NOT EXISTS operational.import_reviews (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id integer NOT NULL REFERENCES operational.import_batches(id),
  row_id integer NOT NULL REFERENCES operational.import_rows(id),
  version integer NOT NULL,
  reviewer_id integer NOT NULL REFERENCES operational.users(id),
  reviewed_at timestamptz NOT NULL DEFAULT now(),
  action text NOT NULL,
  verification_method text,
  detail jsonb NOT NULL
);
GRANT SELECT,INSERT ON operational.import_source_links,operational.import_operations,operational.import_reviews TO amal_app;
GRANT USAGE,SELECT ON SEQUENCE operational.import_reviews_id_seq TO amal_app;
COMMIT;
