SELECT pg_advisory_xact_lock(761910);
CREATE TABLE IF NOT EXISTS operational.waitlist_entries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  patient_id integer NOT NULL REFERENCES operational.patients(patient_id),
  doctor_id integer NOT NULL,
  weekdays integer[] NOT NULL CHECK(cardinality(weekdays) BETWEEN 1 AND 7 AND weekdays <@ ARRAY[0,1,2,3,4,5,6] AND array_position(weekdays,NULL) IS NULL),
  window_start text NOT NULL CHECK(window_start ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  window_end text NOT NULL CHECK(window_end ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' AND window_start<window_end),
  requested_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','fulfilled')),
  created_by integer NOT NULL REFERENCES operational.users(id),
  UNIQUE(id,clinic_id,doctor_id,patient_id),
  FOREIGN KEY(doctor_id,clinic_id) REFERENCES operational.doctors(doctor_id,clinic_id)
);
CREATE INDEX IF NOT EXISTS waitlist_fifo ON operational.waitlist_entries(clinic_id,doctor_id,requested_at,id) WHERE status='active';
CREATE TABLE IF NOT EXISTS operational.waitlist_opportunities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  doctor_id integer NOT NULL,
  source_appointment_id integer NOT NULL REFERENCES operational.appointments(appointment_id),
  cancellation_version integer NOT NULL CHECK(cancellation_version>1),
  cancellation_op_id uuid NOT NULL UNIQUE,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL CHECK(ends_at>starts_at),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  status text NOT NULL DEFAULT 'open' CHECK(status IN ('open','fulfilled','unavailable','exhausted')),
  UNIQUE(source_appointment_id,cancellation_version),
  UNIQUE(id,clinic_id,doctor_id),
  FOREIGN KEY(doctor_id,clinic_id) REFERENCES operational.doctors(doctor_id,clinic_id)
);
CREATE TABLE IF NOT EXISTS operational.waitlist_offers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  doctor_id integer NOT NULL,
  patient_id integer NOT NULL REFERENCES operational.patients(patient_id),
  entry_id integer NOT NULL,
  opportunity_id integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','accepted','declined','expired','unavailable')),
  appointment_id integer REFERENCES operational.appointments(appointment_id),
  CHECK(expires_at=created_at+interval '15 minutes'),
  CHECK((status='accepted')=(appointment_id IS NOT NULL)),
  UNIQUE(opportunity_id,entry_id),
  UNIQUE(id,patient_id,clinic_id),
  FOREIGN KEY(appointment_id,patient_id,clinic_id) REFERENCES operational.appointments(appointment_id,patient_id,clinic_id),
  FOREIGN KEY(entry_id,clinic_id,doctor_id,patient_id) REFERENCES operational.waitlist_entries(id,clinic_id,doctor_id,patient_id),
  FOREIGN KEY(opportunity_id,clinic_id,doctor_id) REFERENCES operational.waitlist_opportunities(id,clinic_id,doctor_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS waitlist_one_opportunity_offer ON operational.waitlist_offers(opportunity_id) WHERE status='active';
CREATE UNIQUE INDEX IF NOT EXISTS waitlist_one_entry_offer ON operational.waitlist_offers(entry_id) WHERE status='active';
CREATE INDEX IF NOT EXISTS waitlist_expiry ON operational.waitlist_offers(expires_at,id) WHERE status='active';
CREATE TABLE IF NOT EXISTS operational.waitlist_operations (
  client_op_id uuid PRIMARY KEY,
  actor_id integer NOT NULL REFERENCES operational.users(id),
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  device_id integer REFERENCES operational.devices(id),
  payload_hash text NOT NULL,
  result jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS operational.waitlist_transitions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  actor_id integer REFERENCES operational.users(id),
  entry_id integer REFERENCES operational.waitlist_entries(id),
  opportunity_id integer REFERENCES operational.waitlist_opportunities(id),
  offer_id integer REFERENCES operational.waitlist_offers(id),
  event text NOT NULL,
  reason text,
  occurred_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE OR REPLACE FUNCTION operational.guard_waitlist_history() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
  IF TG_OP='DELETE' AND current_user='amal_demo_reset' THEN RETURN OLD; END IF;
  RAISE EXCEPTION 'Waitlist history is append-only; privileged demo reset may DELETE only' USING ERRCODE='42501';
END $$;
DROP TRIGGER IF EXISTS waitlist_history_immutable ON operational.waitlist_transitions;
CREATE TRIGGER waitlist_history_immutable BEFORE UPDATE OR DELETE ON operational.waitlist_transitions
  FOR EACH ROW EXECUTE FUNCTION operational.guard_waitlist_history();
DROP TRIGGER IF EXISTS waitlist_history_no_truncate ON operational.waitlist_transitions;
CREATE TRIGGER waitlist_history_no_truncate BEFORE TRUNCATE ON operational.waitlist_transitions
  FOR EACH STATEMENT EXECUTE FUNCTION operational.guard_waitlist_history();
ALTER TABLE operational.notifications ADD COLUMN IF NOT EXISTS waitlist_offer_id integer REFERENCES operational.waitlist_offers(id);
DO $$ BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conname='notifications_waitlist_patient_clinic_fk' AND conrelid='operational.notifications'::regclass) THEN
    ALTER TABLE operational.notifications ADD CONSTRAINT notifications_waitlist_patient_clinic_fk
      FOREIGN KEY(waitlist_offer_id,patient_id,clinic_id) REFERENCES operational.waitlist_offers(id,patient_id,clinic_id);
  END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS notifications_waitlist_identity ON operational.notifications(waitlist_offer_id) WHERE waitlist_offer_id IS NOT NULL;
ALTER TABLE operational.notifications DROP CONSTRAINT IF EXISTS notifications_waitlist_shape;
ALTER TABLE operational.notifications ADD CONSTRAINT notifications_waitlist_shape CHECK(waitlist_offer_id IS NULL OR
  (schedule_version IS NULL AND appointment_id IS NULL AND message_key='waitlist.offer' AND text_ar IS NOT NULL AND text_en IS NOT NULL));
GRANT SELECT,INSERT,UPDATE ON operational.waitlist_entries,operational.waitlist_opportunities,operational.waitlist_offers TO amal_app;
GRANT SELECT,INSERT ON operational.waitlist_operations,operational.waitlist_transitions TO amal_app;
GRANT SELECT,DELETE ON operational.waitlist_entries,operational.waitlist_opportunities,operational.waitlist_offers,
  operational.waitlist_operations,operational.waitlist_transitions TO amal_demo_reset;
GRANT USAGE,SELECT ON SEQUENCE operational.waitlist_entries_id_seq,operational.waitlist_opportunities_id_seq,
  operational.waitlist_offers_id_seq,operational.waitlist_transitions_id_seq TO amal_app;
REVOKE ALL ON FUNCTION operational.guard_waitlist_history() FROM PUBLIC;
COMMIT;
