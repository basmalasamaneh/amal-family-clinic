CREATE TABLE IF NOT EXISTS operational.visit_addenda (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id integer NOT NULL REFERENCES operational.patient_visit_history(visit_id),
  doctor_id integer NOT NULL,
  clinic_id integer NOT NULL,
  note text NOT NULL CHECK(length(btrim(note))>0 AND length(note)<=10000),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  FOREIGN KEY(doctor_id,clinic_id) REFERENCES operational.doctors(doctor_id,clinic_id)
);
CREATE INDEX IF NOT EXISTS visit_addenda_visit_idx ON operational.visit_addenda(visit_id,id);
CREATE TABLE IF NOT EXISTS operational.clinical_write_operations (
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  client_op_id text NOT NULL CHECK(length(client_op_id) BETWEEN 1 AND 200),
  actor_id integer NOT NULL REFERENCES operational.users(id),
  patient_id integer NOT NULL REFERENCES operational.patients(patient_id),
  request_hash text NOT NULL CHECK(request_hash ~ '^[a-f0-9]{64}$'),
  result jsonb NOT NULL CHECK(jsonb_typeof(result)='object'),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY(clinic_id,client_op_id)
);
