-- Applied once by the administrative migration runner, in its transaction.
-- This migration never changes, grants on, or reads the six public seed tables.
CREATE SCHEMA operational;
REVOKE ALL ON SCHEMA operational FROM PUBLIC;

CREATE TYPE operational.network_mode AS ENUM ('full','lite');
CREATE TYPE operational.user_role AS ENUM ('administrator','doctor','receptionist');
CREATE TYPE operational.locale AS ENUM ('ar','en');
CREATE TYPE operational.theme AS ENUM ('light','dark');
CREATE TYPE operational.conflict_state AS ENUM ('none','flagged','resolved');
CREATE TYPE operational.consent_level AS ENUM ('none','basic','clinical');
CREATE TYPE operational.consent_given_by AS ENUM ('patient','guardian');
CREATE TYPE operational.alert_kind AS ENUM ('medication','allergy','condition');
CREATE TYPE operational.sync_status AS ENUM ('pending','applied','conflict','rejected');
CREATE TYPE operational.import_batch_status AS ENUM ('review_required','reviewed','committed');
CREATE TYPE operational.import_review_state AS ENUM ('review_required','confirmed','rejected');
CREATE TYPE operational.import_chosen_action AS ENUM ('create','link','skip');
CREATE TYPE operational.merge_status AS ENUM ('review_required','not_a_match','confirmed');
CREATE TYPE operational.notification_status AS ENUM ('pending','simulated','cancelled');

CREATE TABLE operational.clinics (
  clinic_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_name text NOT NULL,
  city text NOT NULL,
  booking_method text NOT NULL,
  slot_minutes integer NOT NULL DEFAULT 30,
  working_days integer[] NOT NULL DEFAULT ARRAY[0,1,2,3,4,5,6],
  open_time time NOT NULL DEFAULT '08:00',
  close_time time NOT NULL DEFAULT '17:00',
  network_mode operational.network_mode NOT NULL DEFAULT 'full',
  joined_at timestamptz NOT NULL DEFAULT now(),
  timezone text NOT NULL DEFAULT 'Asia/Hebron',
  CONSTRAINT clinics_slot_minutes_check CHECK (slot_minutes BETWEEN 1 AND 1440),
  CONSTRAINT clinics_hours_check CHECK (open_time < close_time),
  CONSTRAINT clinics_working_days_check CHECK (
    cardinality(working_days) BETWEEN 1 AND 7
    AND working_days <@ ARRAY[0,1,2,3,4,5,6]::integer[]
    AND array_position(working_days, NULL) IS NULL
  ),
  CONSTRAINT clinics_timezone_check CHECK (length(btrim(timezone)) > 0)
);

CREATE TABLE operational.doctors (
  doctor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_name text NOT NULL,
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  specialty text NOT NULL,
  email text NOT NULL UNIQUE,
  user_id integer UNIQUE,
  CONSTRAINT doctors_id_clinic_unique UNIQUE (doctor_id, clinic_id),
  CONSTRAINT doctors_email_check CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$')
);

CREATE TABLE operational.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_key text UNIQUE,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role operational.user_role NOT NULL,
  clinic_id integer REFERENCES operational.clinics(clinic_id),
  doctor_id integer UNIQUE,
  pin_hash text,
  locale operational.locale NOT NULL DEFAULT 'ar',
  theme operational.theme NOT NULL DEFAULT 'light',
  last_login timestamptz,
  CONSTRAINT users_doctor_id_fk FOREIGN KEY (doctor_id) REFERENCES operational.doctors(doctor_id) DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT users_doctor_clinic_fk FOREIGN KEY (doctor_id, clinic_id) REFERENCES operational.doctors(doctor_id, clinic_id) DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT users_role_assignment_check CHECK (
    (role = 'administrator' AND doctor_id IS NULL)
    OR (role = 'receptionist' AND clinic_id IS NOT NULL AND doctor_id IS NULL)
    OR (role = 'doctor' AND clinic_id IS NOT NULL AND doctor_id IS NOT NULL)
  ),
  CONSTRAINT users_email_check CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
  CONSTRAINT users_hashes_check CHECK (length(btrim(password_hash)) > 0 AND (pin_hash IS NULL OR length(btrim(pin_hash)) > 0))
);
ALTER TABLE operational.doctors ADD CONSTRAINT doctors_user_id_fk
  FOREIGN KEY (user_id) REFERENCES operational.users(id) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE operational.devices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_key text UNIQUE,
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  label text NOT NULL,
  registered_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT devices_id_clinic_unique UNIQUE (id, clinic_id),
  CONSTRAINT devices_label_check CHECK (label ~ '^[a-z][A-Za-z0-9_.-]*$')
);

CREATE TABLE operational.patients (
  patient_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_name text NOT NULL,
  phone text NOT NULL,
  dob date NOT NULL,
  name_normalized text NOT NULL,
  minor_as_of date NOT NULL DEFAULT CURRENT_DATE,
  is_minor boolean GENERATED ALWAYS AS (minor_as_of < (dob + interval '18 years')::date) STORED,
  guardian_name text,
  guardian_relation text,
  merged_into_id integer REFERENCES operational.patients(patient_id),
  CONSTRAINT patients_dob_check CHECK (dob <= minor_as_of),
  CONSTRAINT patients_name_phone_check CHECK (length(btrim(patient_name)) > 0 AND length(btrim(name_normalized)) > 0 AND length(btrim(phone)) > 0),
  CONSTRAINT patients_guardian_check CHECK (
    (guardian_name IS NULL AND guardian_relation IS NULL)
    OR (guardian_name IS NOT NULL AND guardian_relation IS NOT NULL AND length(btrim(guardian_name)) > 0 AND length(btrim(guardian_relation)) > 0)
  ),
  CONSTRAINT patients_merge_self_check CHECK (merged_into_id IS NULL OR merged_into_id <> patient_id)
);

CREATE TABLE operational.appointments (
  appointment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id integer NOT NULL REFERENCES operational.clinics(clinic_id),
  doctor_id integer NOT NULL REFERENCES operational.doctors(doctor_id),
  patient_id integer NOT NULL REFERENCES operational.patients(patient_id),
  scheduled_at timestamptz NOT NULL,
  booking_method text NOT NULL,
  status text NOT NULL,
  duration_minutes integer NOT NULL DEFAULT 30,
  source_ref text UNIQUE,
  client_op_id text UNIQUE,
  conflict_state operational.conflict_state NOT NULL DEFAULT 'none',
  created_by integer REFERENCES operational.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  cancel_reason text,
  CONSTRAINT appointments_id_patient_clinic_unique UNIQUE (appointment_id, patient_id, clinic_id),
  CONSTRAINT appointments_doctor_clinic_fk FOREIGN KEY (doctor_id, clinic_id) REFERENCES operational.doctors(doctor_id, clinic_id),
  CONSTRAINT appointments_duration_check CHECK (duration_minutes BETWEEN 1 AND 1440),
  CONSTRAINT appointments_status_check CHECK (status IN ('booked','completed','double_booked','no_show','cancelled')),
  CONSTRAINT appointments_times_check CHECK (updated_at >= created_at),
  CONSTRAINT appointments_refs_check CHECK ((source_ref IS NULL OR length(btrim(source_ref)) > 0) AND (client_op_id IS NULL OR length(btrim(client_op_id)) > 0))
);
-- Deliberately non-unique: historical exact-time collisions are valid source facts.
