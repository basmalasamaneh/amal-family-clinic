-- Deferred final-state checks allow doctors and users to be assigned in either
-- order within one transaction, but not to commit inconsistent reciprocal links.
CREATE FUNCTION operational.check_doctor_user_links() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM operational.doctors d
    LEFT JOIN operational.users u ON u.id = d.user_id
    WHERE d.user_id IS NOT NULL
      AND (u.id IS NULL OR u.role <> 'doctor' OR u.doctor_id IS DISTINCT FROM d.doctor_id OR u.clinic_id IS DISTINCT FROM d.clinic_id)
  ) OR EXISTS (
    SELECT 1 FROM operational.users u
    LEFT JOIN operational.doctors d ON d.doctor_id = u.doctor_id
    WHERE u.role = 'doctor' AND (d.doctor_id IS NULL OR d.user_id IS DISTINCT FROM u.id OR d.clinic_id IS DISTINCT FROM u.clinic_id)
  ) THEN
    RAISE EXCEPTION 'Doctor/user assignments must be reciprocal and in the same clinic' USING ERRCODE = '23514';
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER doctors_user_consistency AFTER INSERT OR UPDATE OR DELETE ON operational.doctors
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_doctor_user_links();
CREATE CONSTRAINT TRIGGER users_doctor_consistency AFTER INSERT OR UPDATE OR DELETE ON operational.users
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_doctor_user_links();

-- A frozen patient minor_as_of is not used for legal consent at another date.
CREATE FUNCTION operational.check_consent_guardian() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM operational.patient_consents c
    JOIN operational.patients p ON p.patient_id = c.patient_id
    WHERE c.given_by = 'patient'
      AND (c.given_at AT TIME ZONE 'Asia/Hebron')::date < (p.dob + interval '18 years')::date
  ) THEN
    RAISE EXCEPTION 'A minor requires guardian-attributed consent at given_at' USING ERRCODE = '23514';
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER consents_guardian_age AFTER INSERT OR UPDATE ON operational.patient_consents
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_consent_guardian();
CREATE CONSTRAINT TRIGGER patients_consent_age AFTER UPDATE ON operational.patients
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_consent_guardian();

CREATE FUNCTION operational.check_alert_provenance() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM operational.visit_alerts a
    JOIN operational.patient_visit_history v ON v.visit_id = a.visit_id
    WHERE a.patient_id <> v.patient_id OR a.source_note_excerpt IS DISTINCT FROM v.diagnosis_notes
  ) THEN
    RAISE EXCEPTION 'Alert must retain the exact source visit note and patient' USING ERRCODE = '23514';
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER alerts_source_provenance AFTER INSERT OR UPDATE ON operational.visit_alerts
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_alert_provenance();
CREATE CONSTRAINT TRIGGER visits_alert_provenance AFTER UPDATE ON operational.patient_visit_history
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_alert_provenance();

CREATE FUNCTION operational.check_import_links() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM operational.import_rows r
    JOIN operational.import_batches b ON b.id = r.batch_id
    LEFT JOIN operational.doctors d ON d.doctor_id = r.confirmed_doctor_id
    LEFT JOIN operational.appointments a ON a.appointment_id = r.appointment_id
    WHERE (r.confirmed_doctor_id IS NOT NULL AND d.clinic_id IS DISTINCT FROM b.clinic_id)
      OR (r.appointment_id IS NOT NULL AND (
        a.patient_id IS DISTINCT FROM r.confirmed_patient_id
        OR a.doctor_id IS DISTINCT FROM r.confirmed_doctor_id
        OR a.clinic_id IS DISTINCT FROM b.clinic_id
      ))
  ) THEN
    RAISE EXCEPTION 'Confirmed import identities and appointment must agree with the batch clinic' USING ERRCODE = '23514';
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER import_rows_link_integrity AFTER INSERT OR UPDATE ON operational.import_rows
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_import_links();
CREATE CONSTRAINT TRIGGER import_batches_link_integrity AFTER UPDATE ON operational.import_batches
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_import_links();
CREATE CONSTRAINT TRIGGER appointments_import_integrity AFTER UPDATE ON operational.appointments
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_import_links();
CREATE CONSTRAINT TRIGGER doctors_import_integrity AFTER UPDATE ON operational.doctors
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION operational.check_import_links();

CREATE FUNCTION operational.check_clinic_settings() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_timezone_names WHERE name = NEW.timezone) THEN
    RAISE EXCEPTION 'Unknown IANA timezone: %', NEW.timezone USING ERRCODE = '23514';
  END IF;
  IF cardinality(NEW.working_days) <> (SELECT count(DISTINCT d) FROM unnest(NEW.working_days) d) THEN
    RAISE EXCEPTION 'Clinic working days must be distinct' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER clinics_settings BEFORE INSERT OR UPDATE ON operational.clinics
  FOR EACH ROW EXECUTE FUNCTION operational.check_clinic_settings();

-- A dedicated NOLOGIN role is the only deletion exception, checked using actual
-- current_user, never a caller-set GUC. No SECURITY DEFINER reset function exists.
CREATE ROLE amal_demo_reset NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
DO $$
BEGIN
  EXECUTE format('GRANT amal_demo_reset TO %I', current_user);
  IF pg_has_role('amal_app', 'amal_demo_reset', 'MEMBER') THEN
    RAISE EXCEPTION 'amal_app must never be a member of amal_demo_reset';
  END IF;
END;
$$;

CREATE FUNCTION operational.guard_audit_log() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF TG_OP = 'DELETE' AND current_user = 'amal_demo_reset' THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION 'Audit log is append-only; privileged demo reset may DELETE only' USING ERRCODE = '42501';
END;
$$;
CREATE TRIGGER audit_append_only BEFORE UPDATE OR DELETE ON operational.audit_log
  FOR EACH ROW EXECUTE FUNCTION operational.guard_audit_log();
CREATE TRIGGER audit_no_truncate BEFORE TRUNCATE ON operational.audit_log
  FOR EACH STATEMENT EXECUTE FUNCTION operational.guard_audit_log();

